vim.opt.runtimepath:prepend(vim.fn.getcwd())
local renderer = require('picker.list')
vim.api.nvim_set_hl(0, 'PickerTestCurrent', { bg = '#112233' })
vim.api.nvim_set_hl(0, 'PickerTestMatch', { bg = '#aa5500' })
local pane = { buf = vim.api.nvim_get_current_buf(), win = vim.api.nvim_get_current_win() }
vim.api.nvim_buf_set_lines(pane.buf, 0, -1, false, { 'before MATCH after', 'second' })
local ns = vim.api.nvim_create_namespace('PickerTestMatch')
vim.api.nvim_buf_set_extmark(pane.buf, ns, 0, 7, {
  end_col = 12,
  hl_group = 'PickerTestMatch',
  priority = 200,
})
vim.cmd('redraw!')
local match_attr = vim.fn.screenattr(1, 8)
local normal_attr = vim.fn.screenattr(1, 1)
local tick = vim.api.nvim_buf_get_changedtick(pane.buf)
renderer.select(pane, 1, 'PickerTestCurrent')
vim.cmd('redraw!')
assert(vim.fn.screenattr(1, 8) == match_attr, 'current background covered match')
assert(vim.fn.screenattr(1, 1) ~= normal_attr, 'current background missing')
assert(vim.fn.screenattr(1, 30) == vim.fn.screenattr(1, 1), 'current background missing after EOL')
renderer.select(pane, 2, 'PickerTestCurrent')
vim.cmd('redraw!')
assert(vim.fn.screenattr(1, 1) == normal_attr, 'old current background leaked')
assert(vim.fn.screenattr(1, 8) == match_attr, 'moving current changed match')
renderer.select(pane, nil)
vim.cmd('redraw!')
assert(vim.fn.screenattr(2, 1) == normal_attr, 'cleared current background leaked')
assert(vim.api.nvim_buf_get_changedtick(pane.buf) == tick, 'selection rewrote content')
print('PASS rendered match/current composition, EOL background, movement and clearing')
