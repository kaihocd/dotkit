vim.opt.runtimepath:prepend(vim.fn.getcwd())
vim.opt.runtimepath:prepend(vim.env.POPUP_NVIM_PATH or '../popup.nvim')
local signs = require('picker.picker.window.signs')
vim.api.nvim_set_hl(0, 'Added', { fg = 0xffffff })
vim.api.nvim_set_hl(0, 'NormalFloat', { bg = 0x000000 })
local staged = assert(signs.marker('staged_new', false))
assert(vim.api.nvim_get_hl(0, { name = staged[2], link = false }).fg == 0x999999)
assert(vim.api.nvim_get_hl(0, { name = staged[2], link = false }).bg == nil)
assert(signs.marker('staged_new', true)[2] == 'Title')
assert(signs.marker('untracked', false)[2] == 'Added')
assert(signs.marker(nil, false) == nil)
vim.api.nvim_set_hl(0, 'NormalFloat', { bg = 0xffffff })
signs.marker('staged_new', false)
assert(vim.api.nvim_get_hl(0, { name = staged[2], link = false }).fg == 0xffffff)
vim.api.nvim_set_hl(0, 'NormalFloat', {})
assert(signs.marker('staged_new', false)[2] == 'Added')
print('PASS staged RGB blending, mark priority, theme repaint and missing-color fallback')
