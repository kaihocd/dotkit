vim.opt.runtimepath:prepend(vim.fn.getcwd())
local Cache = require('picker.picker.preview.cache')
local cache = Cache.new(2, 8)
local lines = { 'abc' }
cache:put('a', '1', lines)
lines[1] = 'changed'
local hit = assert(cache:get('a', '1'))
assert(hit[1] == 'abc')
hit[1] = 'changed again'
assert(cache:get('a', '1')[1] == 'abc')
cache:put('b', '1', { 'def' })
cache:get('a', '1')
cache:put('c', '1', { 'ghi' })
assert(cache:get('b', '1') == nil)
assert(cache:get('a', '2') == nil)
cache:put('c', '2', { string.rep('x', 9) })
assert(cache:get('c', '1') == nil)
cache:put('a', '1', { 'a' })
cache:clear()
assert(cache:get('a', '1') == nil)
local bytes = Cache.new(10, 4)
bytes:put('a', '1', { 'abc' })
bytes:put('b', '1', { 'x' })
assert(bytes:get('a', '1') == nil and bytes:get('b', '1') ~= nil)
print('PASS preview cache copies, recency, file/byte limits, versions and oversized replacement')
