return function(test)
  test('creates, starts and completes with ordered lifecycle events', function()
    local Task = require('cli.task')
    local events = {}
    local task = Task.new({ id = 'one' })
    task:on(function(event)
      events[#events + 1] = event.kind
    end)
    assert(task:status() == 'created')
    assert(task:start() == task)
    assert(task:status() == 'running')
    assert(task:complete({ kind = 'exit', code = 0 }) == true)
    assert(task:status() == 'finished')
    assert(vim.deep_equal(events, { 'start', 'result' }))
    assert(vim.deep_equal(task:result(), { kind = 'exit', code = 0 }))
  end)

  test('streams output, supports cancellation, and accepts the eventual result', function()
    local Task = require('cli.task')
    local events = {}
    local task = Task.new()
    task:on(function(event)
      events[#events + 1] = event.kind .. (event.stream and ':' .. event.stream or '')
    end)
    task:start()
    assert(task:output('stdout', 'out') == true)
    assert(task:output('stderr', 'err') == true)
    assert(task:cancel() == true)
    assert(task:status() == 'cancelling')
    assert(task:complete({ kind = 'cancelled' }) == true)
    assert(
      vim.deep_equal(events, { 'start', 'output:stdout', 'output:stderr', 'cancel', 'result' })
    )
    assert(task:output('stdout', 'late') == false)
  end)

  test('ignores duplicate terminal completion and removes listeners after completion', function()
    local Task = require('cli.task')
    local count = 0
    local task = Task.new()
    local unsubscribe = task:on(function()
      count = count + 1
    end)
    task:start()
    assert(task:complete({ kind = 'exit', code = 2 }) == true)
    assert(count == 2)
    local ok = pcall(task.complete, task, { kind = 'exit', code = 0 })
    assert(not ok)
    assert(task:output('stderr', 'late') == false)
    unsubscribe()
    assert(task:result().code == 2)
  end)

  test('rejects invalid lifecycle transitions and result payloads', function()
    local Task = require('cli.task')
    local task = Task.new()
    local function rejects(fn)
      local ok, err = pcall(fn)
      assert(not ok)
      assert(tostring(err):find('cli.task:', 1, true), tostring(err))
    end
    rejects(function()
      task:complete({ kind = 'exit', code = 0 })
    end)
    rejects(function()
      task:cancel()
    end)
    rejects(function()
      task:output('stdin', 'bad')
    end)
    rejects(function()
      task:output('stdout', false)
    end)
    task:start()
    rejects(function()
      task:start()
    end)
    rejects(function()
      task:complete({ kind = 'exit', code = -1 })
    end)
    rejects(function()
      task:complete({ kind = 'delegated', target = 'process' })
    end)
    rejects(function()
      task:complete({ kind = 'error', message = '' })
    end)
    assert(task:complete({ kind = 'error', message = 'failed' }) == true)
  end)

  test('finish completes a task and refuses to complete it twice', function()
    local Task = require('cli.task')
    local task = Task.new()
    local results = 0
    task:on(function(event)
      if event.kind == 'result' then
        results = results + 1
      end
    end)
    task:start()
    assert(task:finish({ kind = 'exit', code = 0 }) == true)
    assert(task:result().code == 0)
    assert(task:finish({ kind = 'exit', code = 9 }) == false)
    assert(task:result().code == 0, 'a late callback must not overwrite the result')
    assert(results == 1)
  end)

  test('finish reports a cancelled task as cancelled whatever the handler saw', function()
    local Task = require('cli.task')
    local task = Task.new()
    task:start()
    task:cancel()
    assert(task:status() == 'cancelling')
    assert(task:finish({ kind = 'exit', code = 0 }) == true)
    assert(vim.deep_equal(task:result(), { kind = 'cancelled' }), vim.inspect(task:result()))
  end)
end
