-- Runs with plain Lua as well as Neovim; no editor state is required.
local lru = dofile('dotfiles/configs/nvim/lua/plugins/explorer/picker/cache/lru.lua')
local cache = lru.new(2, 10)
assert(cache.get('missing') == nil)
cache.put('a', 'A', 4)
cache.put('b', 'B', 4)
assert(cache.get('a') == 'A')
cache.put('c', 'C', 4)
assert(cache.get('b') == nil and cache.get('a') == 'A')
cache.put('a', 'replacement', 6)
assert(cache.get('c') == 'C', 'Replacement must subtract the old weight')
cache.put('d', 'D', 1)
assert(cache.get('a') == nil, 'Weight and recency both determine eviction')
cache.remove('c')
cache.remove('c')
cache.put('e', false, 9)
assert(cache.get('e') == false, 'False is a valid value')
assert(not cache.put('e', 'oversized', 11))
assert(cache.get('e') == nil and cache.get('d') == 'D')
cache.clear()
assert(cache.get('d') == nil)
cache.put('full', 1, 10)
assert(cache.get('full') == 1, 'Clear resets weight accounting')
assert(not lru.new(0).put('a', 1))
assert(not pcall(lru.new, -1))
assert(not pcall(cache.put, 'invalid', 1, -1))
print('PASS standalone LRU')
