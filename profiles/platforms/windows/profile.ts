import { execFileSync } from "node:child_process";
import { join, resolve, win32 } from "node:path";
import type { InstallationEnvironment } from "../../src/platform/environment";
import type { InstallationContext } from "../../src/software";

const repository = resolve(import.meta.dirname, "../../..");

export function profilePath(context: InstallationContext): string {
  const output = execFileSync(
    "powershell.exe",
    [
      "-NoLogo",
      "-NoProfile",
      "-NonInteractive",
      "-Command",
      "[Console]::OutputEncoding = [Text.UTF8Encoding]::new(); " +
        "$pwsh = Get-Command pwsh.exe -ErrorAction SilentlyContinue; " +
        "if ($pwsh) { & $pwsh.Source -NoProfile -NonInteractive -Command '$PROFILE.CurrentUserAllHosts' } " +
        "else { Join-Path ([Environment]::GetFolderPath('MyDocuments')) 'PowerShell\\profile.ps1' }",
    ],
    {
      cwd: context.cwd,
      env: context.environment,
      encoding: "utf8",
      timeout: 30_000,
    },
  ).trim();
  if (!win32.isAbsolute(output))
    throw new Error("Invalid PowerShell profile path.");
  return output;
}

function quote(value: string): string {
  if (/[\r\n\0]/.test(value)) throw new Error("Invalid PowerShell path.");
  return `'${value.replaceAll("'", "''")}'`;
}

export function profileContent(environment: InstallationEnvironment): string {
  const config = environment.xdg.XDG_CONFIG_HOME;
  return [
    "# Generated by Dotkit.",
    `$env:HOME = ${quote(environment.home)}`,
    `$env:XDG_CONFIG_HOME = ${quote(config)}`,
    `$env:XDG_DATA_HOME = ${quote(environment.xdg.XDG_DATA_HOME)}`,
    `$env:XDG_CACHE_HOME = ${quote(environment.xdg.XDG_CACHE_HOME)}`,
    `$env:XDG_STATE_HOME = ${quote(environment.xdg.XDG_STATE_HOME)}`,
    `$env:STARSHIP_CONFIG = ${quote(join(config, "starship.toml"))}`,
    `$env:PATH = ${quote(join(environment.binDirectory, "palette"))} + ';' + $env:PATH`,
    `. ${quote(join(repository, "dotfiles/configs/powershell/profile.ps1"))}`,
    "",
  ].join("\r\n");
}
