import { cliContract } from "../../cli/contract";
import type { CatalogManifest } from "../../src/theme";

/** Renders Palette's Zsh completion from its CLI contract and built catalog. */
export function renderZshCompletion(manifest: CatalogManifest): string {
  const commands = Object.entries(cliContract.commands)
    .map(
      ([name, { description }]) =>
        `      '${escape(name)}:${escape(description)}'`,
    )
    .join("\n");
  const themes = manifest.themes.map((theme) => `'${escape(theme)}'`).join(" ");
  const listJson = cliContract.commands.list.options["--json"];
  const getJson = cliContract.commands.get.options["--json"];

  return `#compdef palette
# Generated by @dotkit/palette. Do not edit.

_palette() {
  local context state line
  local -a commands themes

  commands=(
${commands}
      'help:Show general or command help.'
  )
  themes=(${themes})

  _arguments -C \\
    '1:command:->command' \\
    '*::argument:->argument'

  case $state in
    command)
      _describe 'command' commands
      ;;
    argument)
      case $words[1] in
        list)
          _arguments '${option("--json", listJson)}'
          ;;
        get)
          _arguments '${option("--json", getJson)}' '1:theme:($themes)'
          ;;
        set)
          _describe 'theme' themes
          ;;
        help)
          _describe 'command' commands
          ;;
      esac
      ;;
  esac
}

_palette "$@"
`;
}

function option(name: string, description: string): string {
  return `${name}[${escape(description)}]`;
}

function escape(value: string): string {
  return value
    .replaceAll("'", "'\\''")
    .replaceAll("[", "\\[")
    .replaceAll("]", "\\]");
}
